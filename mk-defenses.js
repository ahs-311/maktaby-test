  function ensurePage() {
    if ($('page-defenses')) return $('page-defenses');
    const ref = $('page-lawsuits') || $('page-cases'); if (!ref) return null;
    if (!$('mkdStyle')) { const s = document.createElement('style'); s.id = 'mkdStyle'; s.textContent = CSS; document.head.appendChild(s); }
    const p = document.createElement('div'); p.className = 'page'; p.id = 'page-defenses';
    ref.parentNode.appendChild(p); return p;
  }
  function ensureNav() {
    if (document.querySelector('.nav-item[data-page="defenses"]')) return;
    const ref = document.querySelector('.nav-item[data-page="lawsuits"]'); if (!ref) return;
    const b = document.createElement('button'); b.className = 'nav-item'; b.dataset.page = 'defenses';
    b.innerHTML = '<span class="icon">🛡️</span> دفوع قضيتي';
    b.addEventListener('click', () => window.showPage('defenses'));
    ref.parentNode.insertBefore(b, ref.nextSibling);
  }
  function render() {
    const p = ensurePage(); if (!p) return;
    const cases = DB.get('cases');
    if (!cur.caseId || !cases.some(c => c.id === cur.caseId)) cur.caseId = (cases[0] || {}).id || '';
    let h = '<div class="mkd-card"><label style="font-weight:700">اختر القضية</label>' +
      '<select id="mkdCase" style="width:100%;margin-top:6px">' + cases.map(c => `<option value="${esc(c.id)}"${c.id === cur.caseId ? ' selected' : ''}>${esc((c.number ? c.number + ' — ' : '') + (c.subject || '').slice(0, 60))}</option>`).join('') + '</select>';
    if (!cases.length) { p.innerHTML = h + '<p>لا توجد قضايا مسجلة بعد. أضف قضية أولًا من صفحة «القضايا».</p></div>'; bind(p); return; }
    cur.st = loadSt(cur.caseId); const x = buildCtx(cur.caseId, cur.st); cur.x = x;
    h += `<div class="mkd-why" style="margin-top:8px">النوع: <b>${esc(x.type)}</b> • الدرجة: ${esc(x.degree || '—')} • المرحلة: ${esc(x.stage || '—')} • الموكل: ${esc(x.client || '—')} (${esc(x.role)}) • الخصم: ${esc(x.opp || '—')}</div>`;
    h += `<div class="mkd-why">${x.lastPast ? 'آخر جلسة: ' + esc(x.lastPast.date) + (x.lastPast.outcome ? ' — ' + esc(x.lastPast.outcome) : '') + ' (منذ ' + x.daysSinceLast + ' يومًا)' : 'لا جلسات مسجلة'}${x.hasFuture ? ' • توجد جلسة قادمة' : ''}</div>`;
    h += `<div style="margin-top:8px;font-size:13px">أنت في هذه القضية: <button class="btn btn-sm ${x.side === 'D' ? 'btn-primary' : 'btn-outline'}" data-act="side" data-v="D">${x.type === 'جنائي' ? 'متهم / دفاع' : 'مدعى عليه (ندفع)'}</button> <button class="btn btn-sm ${x.side === 'P' ? 'btn-primary' : 'btn-outline'}" data-act="side" data-v="P">${x.type === 'جنائي' ? 'مجني عليه / مدعٍ مدني' : 'مدعي'}</button></div></div>`;
    if (x.type === 'جنائي' && x.side === 'P') h += '<div class="mkd-card mkd-warn">الأداة تقترح في القضايا الجنائية دفوع جانب المتهم فقط؛ اختر «متهم / دفاع» لعرضها.</div>';
    h += '<div class="mkd-card"><label style="font-weight:700">مجريات القضية (اكتب ما حدث بإيجاز)</label>' +
      '<textarea id="mkdNotes" rows="4" style="width:100%;box-sizing:border-box;margin-top:6px" placeholder="مثال: أُعلنتُ بالصحيفة على عنوان قديم… الخصم يستند لإيصال أنكر توقيعي عليه… مضت سنوات دون مطالبة…">' + esc(cur.st.notes || '') + '</textarea></div>';
    const qs = FACTS.filter(f => f.t.indexOf(x.type) >= 0);
    h += '<div class="mkd-card"><label style="font-weight:700">أسئلة سريعة (تضبط الاقتراحات)</label>' + qs.map(f => {
      const v = x.f[f.id] || '';
      return `<div class="mkd-q"><span>${esc(f.q)}</span><span class="opt">${[['y', 'نعم'], ['n', 'لا'], ['', '؟']].map(o => `<button data-act="fact" data-id="${f.id}" data-v="${o[0]}" class="${v === o[0] ? 'on' : ''}">${o[1]}</button>`).join('')}</span></div>`;
    }).join('') + '</div>';
    h += '<div style="margin-bottom:12px"><button class="btn btn-primary" data-act="analyze">🔍 حلّل واقترح الدفوع</button></div><div id="mkdOut"></div>';
    p.innerHTML = h; bind(p);
    if (cur.items) showResults();
  }
  function bind(p) {
    const sel = $('mkdCase'); if (sel) sel.onchange = () => { cur.caseId = sel.value; cur.items = null; render(); };
    p.onclick = e => {
      const b = e.target.closest('[data-act]'); if (!b) return; const a = b.dataset.act;
      if (a === 'fact') { cur.st.facts[b.dataset.id] = b.dataset.v; syncNotes(); saveSt(cur.st); render(); }
      else if (a === 'side') { cur.st.side = b.dataset.v; syncNotes(); saveSt(cur.st); cur.items = null; render(); }
      else if (a === 'analyze') { syncNotes(); saveSt(cur.st); run(); }
      else if (a === 'memo') makeMemo();
      else if (a === 'save') { collectPicks(); saveSt(cur.st); toast('تم حفظ التحليل على هذا الجهاز'); }
      else if (a === 'ai') askAI();
    };
  }
  function syncNotes() { const t = $('mkdNotes'); if (t) cur.st.notes = t.value; }
  async function run() {
    const out = $('mkdOut'); out.innerHTML = '<div class="mkd-card">⏳ جارٍ التحليل ومطابقة النصوص بالمكتبة…</div>';
    cur.x = buildCtx(cur.caseId, cur.st); cur.items = analyze(cur.x);
    await Promise.all(cur.items.map(async it => { it.bs = await Promise.all((it.d.basis || []).map(resolveBasis)); }));
    showResults();
    const o = $('mkdOut'); if (o && o.scrollIntoView) o.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }
  function showResults() {
    const out = $('mkdOut'); if (!out) return; const items = cur.items || [];
    if (!items.length) { out.innerHTML = '<div class="mkd-card">لم تظهر دفوع مطابقة. أجب عن الأسئلة السريعة أو اكتب المجريات ثم أعد التحليل.</div>'; return; }
    const picked = cur.st.picked;
    out.innerHTML = '<div class="mkd-card" style="font-size:12px">⚠️ مسودات آلية قائمة على قواعد وعلى نصوص المكتبة: راجعها وتأكد من سريان النص وتعديلاته قبل الاعتماد. الدرجة تعكس قوة الصلة بما أدخلته.</div>' +
      items.map(it => {
        const d = it.d, on = picked ? picked.indexOf(d.id) >= 0 : it.s >= 3;
        const bs = (it.bs || []).map(b => b.ok ? `<div class="mkd-basis"><b>${esc(b.law)} — م ${b.art}</b> (${esc(b.label)}):<br>${esc(b.text)}</div>` : `<div class="mkd-warn">لم يُعثر على نص مؤكد لـ «${esc(b.label)}» في المكتبة — راجعه يدويًا.</div>`).join('');
        return `<div class="mkd-item"><label style="display:flex;gap:8px;align-items:flex-start"><input type="checkbox" class="mkdPick" data-id="${d.id}" ${on ? 'checked' : ''} style="width:auto;margin-top:4px"><span><h4>${esc(d.title)}<span class="mkd-badge">${esc(d.kind)}</span><span class="mkd-badge">صلة: ${it.s >= 6 ? 'قوية' : it.s >= 3 ? 'متوسطة' : 'عامة'}</span></h4></span></label>` +
          `<div class="mkd-why">${it.why.map(esc).join(' • ')}</div><details><summary style="cursor:pointer;font-size:13px">الشرح والسند</summary><p style="font-size:13.5px;line-height:1.9">${esc(d.what)}</p><p style="font-size:13.5px;line-height:1.9"><b>تطبيقه على قضيتك:</b> ${esc(d.how(cur.x))}</p>${bs}${d.tip ? `<div class="mkd-warn">💡 ${esc(d.tip)}</div>` : ''}</details></div>`;
      }).join('') +
      '<div class="mkd-bar"><button class="btn btn-primary" data-act="memo">📄 إنشاء مذكرة من المحدد</button><button class="btn btn-outline" data-act="save">💾 حفظ</button>' + (window.MK_AI && MK_AI.registerTask ? '<button class="btn btn-outline" data-act="ai">🤖 دفوع إضافية بالمساعد</button>' : '') + '</div>';
  }
  function collectPicks() { cur.st.picked = Array.prototype.map.call(document.querySelectorAll('.mkdPick:checked'), i => i.dataset.id); return cur.st.picked; }
  async function makeMemo() {
    const ids = collectPicks(); const chosen = (cur.items || []).filter(i => ids.indexOf(i.d.id) >= 0);
    if (!chosen.length) return alert('اختر دفعًا واحدًا على الأقل.');
    if (!window.DQ_EDITOR) return alert('المحرر غير متاح.');
    saveSt(cur.st);
    chosen.sort((a, b) => a.d.order - b.d.order);
    const html = await memoHtml(cur.x, chosen);
    DQ_EDITOR.ui.open({ kind: 'form', title: 'مذكرة دفاع — ' + (cur.x.number || cur.x.subject || '').toString().slice(0, 50), html: html, tpl: 'مذكرة دفاع', caseId: cur.x.id, clientId: cur.x.clientId });
  }
  function askAI() {
    try {
      MK_AI.registerTask({ id: 'defenses', label: 'دفوع إضافية', lib: true, instr: 'اقترح دفوعًا إضافية محتملة لهذه القضية استنادًا إلى نصوص المكتبة المرفقة فقط، واذكر رقم المادة واسم القانون، دون اختراع.' });
      const x = cur.x; MK_AI.open({ task: 'defenses' });
      setTimeout(() => { const i = document.getElementById('mkAiIn'); if (i) i.value = `نوع القضية: ${x.type}. المحكمة: ${x.court}. الموضوع: ${x.subject}. المجريات: ${cur.st.notes || ''}`; }, 150);
    } catch (e) { }
  }

